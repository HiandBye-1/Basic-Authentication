package HTTP;

public class Employee {
    private int id;
    private String name;

    public Employee(){

    }
    public void setID(int id){
        this.id = id;
    }
    public void setName(String name){
        this.name = name;
    }

    public int getID(){
        return id;
    }
    public String getName(){
        return name;
    }
}
